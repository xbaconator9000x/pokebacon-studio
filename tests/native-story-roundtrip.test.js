import test from 'node:test';
import assert from 'node:assert/strict';
import {syntheticROM} from '../scripts/synthetic-map-rom.mjs';
import {GbaMaps} from '../dist/rom.js';
import {compileScript} from '../dist/script-engine.js';
import {indexNativeStory,installNativeStoryEdits,refreshNativeStory} from '../dist/native-story.js';
import {RomOutput} from '../dist/rom-writer.js';
import {newProject,validateProject} from '../dist/model.js';
import {planSave,savedProjectKeys,assembleSavedProject} from '../dist/project-store.js';
test('existing native dialogue survives project storage and native relocation while unknown commands remain unchanged',async()=>{
 const bytes=syntheticROM(),source='@start:\nmessage @text\ncall @unknown\nend\n@unknown:\n.byte 0xFF\n@text:\n= Ren: Find the key.$\n';
 const built=compileScript(source,0x5000,'frlg');bytes.set(built.bytes,0x5000);new DataView(bytes.buffer).setUint32(0x3060,0x08005000,true);
 const reader=await new GbaMaps(bytes).discover(),g=await indexNativeStory(reader,{mapKeys:['0.0']}),root=g.roots.find(r=>r.kind==='npcs');
 assert.ok(root);assert.ok(Object.values(g.nodes).some(n=>n.opaque));
 const row=Object.values(g.texts)[0],project=newProject('Native event fixture');
 project.nativeStory={fixture:g};g.edits.texts[row.at]={original:row.original,text:'Ren: Bring the medicine kit. Then find the Aipom key.'};
 validateProject(project,[]);
 const plan=planSave(project),parts=new Map(plan.parts.map(p=>[p.id,structuredClone(p.value)]));
 const reopened=assembleSavedProject(structuredClone(plan.header),savedProjectKeys(plan.header).map(id=>parts.get(id)));
 assert.equal(reopened.nativeStory.fixture.edits.texts[row.at].text,g.edits.texts[row.at].text);
 const output=new RomOutput(bytes);await installNativeStoryEdits(reopened,reader,'fixture',output);
 assert.deepEqual(reader.bytes,bytes,'source immutable');
 const unknown=Object.values(g.nodes).find(n=>n.opaque);assert.equal(output.bytes[unknown.at],255);
 assert.equal(new DataView(output.bytes.buffer).getUint32(0x3060,true),0x08005000,'event binding unchanged');
 const exported=await new GbaMaps(output.bytes).discover(),fresh=await refreshNativeStory(g,exported);
 assert.equal(Object.keys(fresh.edits.texts).length,0,'already applied dialogue is not replayed');
 assert.ok(Object.values(fresh.texts).some(t=>t.text===g.edits.texts[row.at].text));
 assert.deepEqual(output.bytes.slice(0x5005,0x500b),bytes.slice(0x5005,0x500b),'unknown call and terminator intact');
});
