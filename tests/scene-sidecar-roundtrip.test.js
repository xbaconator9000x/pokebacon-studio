import test from 'node:test';
import assert from 'node:assert/strict';
import {syntheticROM} from '../scripts/synthetic-map-rom.mjs';
import {GbaMaps} from '../dist/rom.js';
import {compileScript} from '../dist/script-engine.js';
import {indexNativeStory} from '../dist/native-story.js';
import {newProject} from '../dist/model.js';
import {newScene,prepareScene} from '../dist/authoring-model.js';
import {addScenePage,enableScenePages} from '../dist/scene-pages.js';
import {addQuestFlag} from '../dist/quest-model.js';
import {sceneSource} from '../dist/scene-compiler.js';
import {installQuest,QUEST_SOURCE_SHA} from '../dist/quest-runtime.js';
import {createROMProjectSidecar,restoreROMProjectSidecar,resolveROMExportSource,romFingerprint} from '../dist/rom-project.js';
const BASE=0x08000000;
function buildFixture(){
 const source=syntheticROM(),view=new DataView(source.buffer);
 source[0x3000]=1;view.setUint32(0x3004,BASE+0x3200,true);
 source[0x3200]=1;
 source.set(compileScript('@start:\nmessage @text\nend\n@text:\n= The original gate keeper.$\n',0x5000,'frlg').bytes,0x5000);
 view.setUint32(0x3210,BASE+0x5000,true);
 const project=newProject('Shattered scene/quest integrity fixture');
 const map=project.maps[0],event=newScene(project,2,2);
 map.rom={key:'0.0',sourceId:'source-fixture',engine:'frlg'};
 event.rom={type:'npc',index:0};event.title='Gate keeper';
 const flag=addQuestFlag(project,'Aipom key recovered');
 enableScenePages(event.runtime,()=> 'base-page');
 event.runtime.pages[0].steps=[{id:'first',type:'say',text:'Bring back the key.'}];
 const page=addScenePage(event.runtime,()=> 'page-2');
 page.conditions=[{kind:'flag',flagId:flag.id,value:true}];
 page.steps=[{id:'second',type:'say',text:'Welcome back with the key.'}];
 event.runtime.repeat='once';
 prepareScene(project,event);map.markers=[event];
 const runtime=installQuest({allocate(){return 0x1000000;}},QUEST_SOURCE_SHA,project.questToken);
 const code=sceneSource(event,{project,map,questRuntime:runtime,questFlags:project.questFlags,gameProfile:{engine:'frlg',itemCount:300,speciesCount:500,trainerCount:400}});
 const authored=compileScript(code,0x6000,'frlg'),compiled=source.slice();
 compiled.set(authored.bytes,0x6000);new DataView(compiled.buffer).setUint32(0x3210,BASE+0x6000,true);
 return{project,event,source,compiled};
}
test('visual quest pages + native event pointer survive ROM sidecar export → reopen → reimport',async()=>{
 const {project,source,compiled,event}=buildFixture();
 const sidecar=await createROMProjectSidecar(compiled,source,project,{sourceId:'source-fixture'});
 assert.equal(sidecar.romRoundTrip.sourceId,'source-fixture');
 assert.equal(sidecar.romRoundTrip.sourceLength,source.length);
 assert.equal(sidecar.maps[0].markers[0].runtime.pages.length,2);
 const restored=await restoreROMProjectSidecar(JSON.parse(JSON.stringify(sidecar)),compiled);
 assert.deepEqual(restored.source,source);
 assert.deepEqual(restored.project.questFlags,project.questFlags);
 assert.deepEqual(restored.project.maps[0].markers[0].runtime.pages,event.runtime.pages);
 assert.equal(restored.project.questToken,project.questToken);
 const resolved=await resolveROMExportSource(sidecar,compiled);
 assert.equal(resolved.sourceId,'source-fixture');
 assert.deepEqual(resolved.source,source);
 assert.equal(await resolveROMExportSource(sidecar,source),null);
 const originalGraph=await indexNativeStory(await new GbaMaps(restored.source).discover(),{mapKeys:['0.0']});
 const playableGraph=await indexNativeStory(await new GbaMaps(compiled).discover(),{mapKeys:['0.0']});
 const old=originalGraph.roots.find(r=>r.kind==='npcs'),updated=playableGraph.roots.find(r=>r.kind==='npcs');
 assert.equal(old.address,0x5000);
 assert.equal(updated.address,0x6000);
 assert.ok(Object.values(playableGraph.texts).some(row=>row.text.includes('Welcome back with the key.')));
});
test('competing ROM and damaged sidecars are rejected without mutating the original project',async()=>{
 const {project,source,compiled}=buildFixture();
 const sidecar=await createROMProjectSidecar(compiled,source,project,{sourceId:'source-fixture'}),snapshot=JSON.stringify(sidecar);
 const other=compiled.slice();other[0x6000]^=0xFF;
 await assert.rejects(restoreROMProjectSidecar(sidecar,other),/does not match|sidecar/i);
 assert.equal(await resolveROMExportSource(sidecar,other),null);
 const corrupt=JSON.parse(snapshot);corrupt.romRoundTrip.sourceGzip='AAAA';
 await assert.rejects(restoreROMProjectSidecar(corrupt,compiled),/damaged|invalid|decompress|unpack|archive|compressed/i);
 assert.equal(JSON.stringify(sidecar),snapshot);
 const retouched=compiled.slice();retouched[0x6001]^=1;
 const later=await createROMProjectSidecar(retouched,source,sidecar,{sourceId:'source-fixture'});
 assert.ok(later.romRoundTrip.compiledFingerprints.includes(await romFingerprint(compiled)));
 assert.ok(later.romRoundTrip.compiledFingerprints.includes(await romFingerprint(retouched)));
 assert.deepEqual((await restoreROMProjectSidecar(later,compiled)).source,source);
});
